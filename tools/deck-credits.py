"""Step 3: write decks/credits.txt (one line per image: name, author or studio, licence + link,
source page) from decks/*/deck.json. CREDITS.md explains it and links here.
Usage: python -I tools/deck-credits.py
"""
import json, os, sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.stdout = open(os.path.join(ROOT, "decks", "credits.txt"), "w", encoding="utf-8", newline="\n")
print("Mystery Face card images: credits and licences (generated by tools/deck-credits.py)")
print("Real people and the Cartoons & Classics cards: free-licence images from Wikimedia Commons.")
print("Movie characters: the studios' own character images (copyright their owners), used for fan play;")
print("each line names the studio and the wiki page the image came from.")
print("Each line: name: author or studio, licence (link), source page.")
print("Cropped and resized to 256x256 WebP; no other changes. Mixed-deck cards are copies of the cards below.")
idx = json.load(open(os.path.join(ROOT, "decks", "index.json"), encoding="utf-8"))
seen = set()
for d in idx:
    if d["id"] == "mixed":
        continue  # every Mixed card is a copy of a card in one of the themed decks
    deck = json.load(open(os.path.join(ROOT, "decks", d["id"], "deck.json"), encoding="utf-8"))
    if not any(p.get("img") for p in deck["people"]):
        continue  # name-tile deck (Movie characters): no pictures to credit
    print("\n## %s (%d)\n" % (deck["title"], len(deck["people"])))
    for p in deck["people"]:
        if p["id"] in seen or not p.get("img"):  # name tiles have no picture
            continue
        seen.add(p["id"])
        c = p["credit"]
        a = c["author"].replace("|", "/").replace("[", "(").replace("]", ")")
        if len(a) > 90:
            a = a[:87] + "..."
        lic = "[%s](%s)" % (c["license"], c["licenseUrl"]) if c.get("licenseUrl") else c["license"]
        print("- **%s**: %s, %s, [source](%s)" % (p["name"], a, lic, c["source"].replace(" ", "_")))
